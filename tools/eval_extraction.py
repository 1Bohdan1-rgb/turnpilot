"""Measure drawing extraction accuracy against the expected answers. Uses the REAL API and costs money.

Runs every drawing in tests/fixtures/drawings/ in three variants: clean PNG, clean PDF and the
"photo" JPG, compares the result with <name>.expected.json and reports accuracy separately for
clean and photo drawings. null in an expected answer means "not on the drawing": null from the
model is then correct, a number is a guess. Output: a table in the console and docs/eval_results.md.

Not part of pytest. Usage:
    python tools/eval_extraction.py            # asks for confirmation first
    python tools/eval_extraction.py --yes      # no confirmation
    python tools/eval_extraction.py --only 02_threaded_shaft --variants png photo
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from types import SimpleNamespace

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from turnpilot import drawing_reader  # noqa: E402
from turnpilot.extraction_schema import DrawingData  # noqa: E402
from turnpilot.services import MATERIAL_ALIASES, match_material  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures" / "drawings"
RESULTS_MD = ROOT / "docs" / "eval_results.md"

# Generated drawings: variant -> (file suffix, file type, group)
VARIANTS = {
    "png": (".png", "png", "clean"),
    "pdf": (".pdf", "pdf", "clean"),
    "photo": (".photo.jpg", "jpeg", "photo"),
}
# Real drawings are named real_*: one file in whatever format it came in, reported as group "real".
REAL_PREFIX = "real_"
REAL_SUFFIXES = {".png": "png", ".jpg": "jpeg", ".jpeg": "jpeg", ".pdf": "pdf"}
GROUPS = ("clean", "photo", "real")
# Feature metrics are counted once per expected feature, part metrics once per drawing.
FEATURE_NUMBER_METRICS = ("diameter", "start_diameter", "length", "pitch", "radius")
FEATURE_METRICS = FEATURE_NUMBER_METRICS + ("tolerance", "ra")
PART_METRICS = ("material", "overall_length", "general_ra")
METRICS = FEATURE_METRICS + PART_METRICS
NUMBER_TOLERANCE = 0.01  # mm / µm

# Written into every report; keep it up to date when the prompt or the drawings change.
KNOWN_LIMITATIONS = """- **Ra on a leader in a sectioned bushing.** On `03_bushing` the bore's Ra 1.6 sits on a leader whose
  arrow touches the bore wall, with the symbol on a shelf outside the part. The model consistently
  assigns it to the outside diameter Ø50 instead, even with an explicit prompt rule. The review screen
  compensates: when a part has a bore without Ra and an OD with Ra, both rows get the warning
  "Ra may belong to the bore — check".
- **Occasional extra face.** The model sometimes adds a `face` feature although the prompt says not to
  unless it is annotated (seen once in 15 calls). On Confirm the "Add facing" checkbox no longer adds
  a second one, and the checkbox is unticked by default when the drawing rows already have a face.
- **Synthetic test set, prompt tuned on it.** The five drawings are generated by
  `tools/generate_drawings.py` with one layout style, clean fonts and simple parts; the "photo" variant
  only simulates rotation, blur, noise and JPEG. The prompt rules (threaded sections, THRU bores, Ra on
  leaders) were written while looking at failures on these same drawings, so these numbers are an
  optimistic, in-sample estimate. Real drawings (other CAD styles, hand-drawn notes, scans, multi-view
  sheets, GD&T) need a separate, untouched test set before the accuracy can be trusted.
"""


@dataclass
class Score:
    correct: int = 0
    total: int = 0

    def add(self, ok: bool):
        self.correct += int(ok)
        self.total += 1

    @property
    def pct(self):
        return 100 * self.correct / self.total if self.total else None


@dataclass
class RunResult:
    drawing: str
    variant: str
    group: str
    scores: dict = field(default_factory=lambda: {m: Score() for m in METRICS})
    missing: int = 0
    extra: int = 0
    error: str | None = None
    seconds: float = 0.0
    tokens: tuple[int, int] = (0, 0)
    mismatches: list[str] = field(default_factory=list)
    run: int = 1  # repeat number with --repeat


def _same_number(a, b):
    if a is None or b is None:
        return a is None and b is None
    return abs(a - b) <= NUMBER_TOLERANCE


def _norm_tolerance(value):
    if value is None:
        return None
    return value.replace(" ", "").replace("+/-", "±").replace("−", "-")


def _match_features(expected, predicted):
    """Pair each expected feature with the unused predicted feature of the same type and closest diameter."""
    unused = list(predicted)
    pairs = []
    for exp in expected:
        candidates = [p for p in unused if p.type == exp.type]
        if not candidates:
            pairs.append((exp, None))
            continue
        best = min(candidates, key=lambda p: abs((p.diameter or 0) - (exp.diameter or 0)))
        unused.remove(best)
        pairs.append((exp, best))
    return pairs, unused


def _material_key(text):
    materials = [SimpleNamespace(name=name) for name in MATERIAL_ALIASES]
    found = match_material(text, materials)
    return found.name if found else (text or "").strip().lower() or None


def score(expected: DrawingData, predicted: DrawingData, result: RunResult):
    pairs, extra = _match_features(expected.features, predicted.features)
    result.extra = len(extra)
    for exp, got in pairs:
        label = f"{exp.type} Ø{exp.diameter:g}" if exp.diameter else exp.type
        if got is None:
            result.missing += 1
            result.mismatches.append(f"missing {label}")
        # Every metric is counted for every expected feature. null in the expected answer means the
        # value is not on the drawing: null from the model is then correct, and a number is a guess.
        for metric in FEATURE_NUMBER_METRICS:
            want = getattr(exp, metric)
            ok = got is not None and _same_number(getattr(got, metric), want)
            result.scores[metric].add(ok)
            if got is not None and not ok:
                result.mismatches.append(f"{label}: {metric} {getattr(got, metric)} (expected {want})")
        tol_ok = got is not None and _norm_tolerance(got.tolerance) == _norm_tolerance(exp.tolerance)
        result.scores["tolerance"].add(tol_ok)
        if got is not None and not tol_ok:
            result.mismatches.append(f"{label}: tolerance {got.tolerance!r} (expected {exp.tolerance!r})")
        ra_ok = got is not None and _same_number(got.ra, exp.ra)
        result.scores["ra"].add(ra_ok)
        if got is not None and not ra_ok:
            result.mismatches.append(f"{label}: Ra {got.ra} (expected {exp.ra})")
    for p in extra:
        result.mismatches.append(f"extra {p.type} Ø{p.diameter}")
    material_ok = _material_key(predicted.material) == _material_key(expected.material)
    result.scores["material"].add(material_ok)
    if not material_ok:
        result.mismatches.append(f"material {predicted.material!r} (expected {expected.material!r})")
    for metric in ("overall_length", "general_ra"):
        want, got = getattr(expected, metric), getattr(predicted, metric)
        ok = _same_number(got, want)
        result.scores[metric].add(ok)
        if not ok:
            result.mismatches.append(f"{metric} {got} (expected {want})")


def real_drawing_file(name):
    """(path, file type) of a real drawing, or None if there is no file for it."""
    for suffix, file_type in REAL_SUFFIXES.items():
        path = FIXTURES / f"{name}{suffix}"
        if path.exists():
            return path, file_type
    return None


def planned_runs(names, variants):
    """(name, variant) pairs to run: all requested variants for generated drawings, one run per real drawing."""
    runs = []
    for name in names:
        if name.startswith(REAL_PREFIX):
            if real_drawing_file(name):
                runs.append((name, "real"))
        else:
            runs += [(name, v) for v in variants if (FIXTURES / f"{name}{VARIANTS[v][0]}").exists()]
    return runs


def run_one(client, model, name, variant, run=1) -> RunResult:
    if variant == "real":
        path, file_type = real_drawing_file(name)
        group = "real"
    else:
        suffix, file_type, group = VARIANTS[variant]
        path = FIXTURES / f"{name}{suffix}"
    result = RunResult(name, variant, group, run=run)
    expected = DrawingData.model_validate_json((FIXTURES / f"{name}.expected.json").read_text(encoding="utf-8"))
    start = time.monotonic()
    try:
        image = drawing_reader.prepare_image(path.read_bytes(), file_type)
        extraction = drawing_reader.extract_drawing(image, client=client, model=model)
        usage = extraction.raw.get("usage", {})
        result.tokens = (usage.get("input_tokens", 0), usage.get("output_tokens", 0))
        score(expected, extraction.data, result)
    except Exception as exc:  # count the whole drawing as wrong, keep going
        result.error = f"{type(exc).__name__}: {exc}"[:300]
        for m in METRICS:
            result.scores[m].total += 1 if m in PART_METRICS else len(expected.features)
    result.seconds = time.monotonic() - start
    return result


def aggregate(results, group):
    """Summed scores for one group (None = all groups)."""
    totals = {m: Score() for m in METRICS}
    for r in results:
        if group is None or r.group == group:
            for m in METRICS:
                totals[m].correct += r.scores[m].correct
                totals[m].total += r.scores[m].total
    return totals


def _pct(score: Score):
    return "—" if score.pct is None else f"{score.pct:.0f}% ({score.correct}/{score.total})"


def _label(metric):
    return {"ra": "Ra", "general_ra": "General Ra"}.get(metric, metric.replace("_", " ").capitalize())


def repeat_table(results):
    """Accuracy per metric for each repeat, then the mean and the min–max spread across repeats."""
    runs = sorted({r.run for r in results})
    per_run = {n: aggregate([r for r in results if r.run == n], None) for n in runs}
    lines = ["| Run | " + " | ".join(_label(m) for m in METRICS) + " |", "|" + "---|" * (len(METRICS) + 1)]
    for n in runs:
        lines.append(f"| {n} | " + " | ".join(_pct(per_run[n][m]) for m in METRICS) + " |")
    means, spreads = [], []
    for m in METRICS:
        values = [per_run[n][m].pct for n in runs if per_run[n][m].pct is not None]
        means.append(f"{sum(values) / len(values):.0f}%" if values else "—")
        spreads.append(f"{min(values):.0f}–{max(values):.0f}%" if values else "—")
    lines.append("| **mean** | " + " | ".join(means) + " |")
    lines.append("| min–max | " + " | ".join(spreads) + " |")
    return "\n".join(lines)


def summary_table(results):
    header = "| Group | " + " | ".join(_label(m) for m in METRICS) + " | Missing | Extra | Errors |"
    lines = [header, "|" + "---|" * (len(METRICS) + 4)]
    for group in GROUPS:
        runs = [r for r in results if r.group == group]
        if not runs:
            continue
        totals = aggregate(results, group)
        lines.append(
            f"| {group} ({len(runs)} runs) | " + " | ".join(_pct(totals[m]) for m in METRICS)
            + f" | {sum(r.missing for r in runs)} | {sum(r.extra for r in runs)} | {sum(bool(r.error) for r in runs)} |"
        )
    return "\n".join(lines)


def detail_table(results):
    lines = ["| Drawing | Variant | Run | " + " | ".join(_label(m) for m in METRICS) + " | Time, s | Tokens in/out |",
             "|" + "---|" * (len(METRICS) + 5)]
    for r in results:
        cells = " | ".join("—" if r.scores[m].pct is None else f"{r.scores[m].pct:.0f}%" for m in METRICS)
        lines.append(f"| {r.drawing} | {r.variant} | {r.run} | {cells} | {r.seconds:.1f} | {r.tokens[0]}/{r.tokens[1]} |")
    return "\n".join(lines)


def write_markdown(results, model, path=None):
    path = path or RESULTS_MD
    problems = [f"- **{r.drawing} / {r.variant} / run {r.run}**: " + (r.error or "; ".join(r.mismatches))
                for r in results if r.error or r.mismatches]
    repeats = ""
    if len({r.run for r in results}) > 1:
        repeats = f"\n## Run to run\n\n{repeat_table(results)}\n"
    text = f"""# Drawing extraction accuracy

Generated by `tools/eval_extraction.py` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC with model `{model}`.

Test drawings: `tests/fixtures/drawings/`. *clean* = PNG and PDF renders and *photo* = rotated,
downscaled, noisy JPEG, both made by `tools/generate_drawings.py`; *real* = real drawings (`real_*`)
with hand-written expected answers. Real drawings without an expected answer are skipped.

Scoring: expected features are paired with extracted ones of the same type (closest diameter).
Feature metrics count for every expected feature, part metrics (material, overall length, general
Ra) once per drawing. `null` in the expected answer means the value is
not on the drawing: `null` from the model is then correct and any number is counted as a guess
(`05_bushing_ambiguous` has no bore length on purpose). A missing feature is wrong on every
metric. Numbers match within {NUMBER_TOLERANCE}.

## Summary

{summary_table(results)}
{repeats}
## Per drawing

{detail_table(results)}

## Differences

{chr(10).join(problems) if problems else "None."}

## Known limitations

{KNOWN_LIMITATIONS}"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--yes", action="store_true", help="do not ask for confirmation")
    parser.add_argument("--only", nargs="*", help="drawing names (default: all)")
    parser.add_argument("--variants", nargs="*", choices=list(VARIANTS), default=list(VARIANTS))
    parser.add_argument("--model", default=None, help="overrides ANTHROPIC_MODEL")
    parser.add_argument("--groups", nargs="*", choices=GROUPS, default=list(GROUPS),
                        help="only these groups, e.g. --groups real")
    parser.add_argument("--repeat", type=int, default=1,
                        help="run everything N times to see how much the answers vary")
    parser.add_argument("--output", type=Path, default=RESULTS_MD,
                        help="report path (use a git-ignored path such as instance/... for real drawings)")
    args = parser.parse_args(argv)

    names = sorted(p.name.removesuffix(".expected.json") for p in FIXTURES.glob("*.expected.json"))
    if args.only:
        names = [n for n in names if n in args.only]
    runs = [(n, v) for n, v in planned_runs(names, args.variants)
            if ("real" if v == "real" else VARIANTS[v][2]) in args.groups]
    runs = [(n, v, k) for k in range(1, args.repeat + 1) for n, v in runs]
    client = drawing_reader.make_client()  # loads .env
    model = args.model or os.environ.get("ANTHROPIC_MODEL") or drawing_reader.DEFAULT_MODEL

    print(f"{len(runs)} API calls with model {model} (roughly 5k input + up to 64k output tokens each).")
    if not args.yes and input("Continue? [y/N] ").strip().lower() != "y":
        print("Cancelled.")
        return 1

    results = []
    for name, variant, run in runs:
        result = run_one(client, model, name, variant, run=run)
        status = result.error or ", ".join(f"{m} {_pct(result.scores[m])}" for m in METRICS)
        print(f"  run {run}  {name:22} {variant:6} {result.seconds:5.1f}s  {status}")
        results.append(result)

    print()
    print(summary_table(results))
    if args.repeat > 1:
        print()
        print(repeat_table(results))
    path = write_markdown(results, model, args.output)
    print(f"\nWritten to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
